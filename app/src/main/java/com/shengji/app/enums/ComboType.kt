package com.shengji.app.enums

/**
 * 牌型枚举
 *
 * 定义升级（拖拉机）游戏中所有合法的出牌牌型。
 * 牌型决定了跟牌的强制规则和轮次比较方式。
 */
enum class ComboType {
    /** 单张：一张牌 */
    SINGLE,

    /** 对子：同点数同有效花色的两张牌 */
    PAIR,

    /**
     * 拖拉机（连对）：同花色、点数连续的若干对子
     *
     * 示例：3344、556677、JJQQKK。
     * 级牌位置跳过形成空心拖拉机，如打 7 时 6688 是拖拉机。
     */
    TRACTOR,

    /**
     * 甩牌：同花色多张牌的混合出牌
     *
     * 可包含单张、对子的任意组合，如 ♠3 ♠5 ♠5 ♠K。
     * 前提：其余三家手中无更大的同花色牌。
     */
    SLINGSHOT,

    /** 非法出牌：不满足任何合法牌型 */
    INVALID
}
